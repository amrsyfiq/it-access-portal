-- IT Access Request Portal - initial schema (Oracle 12c+; developed against Oracle Database Free 23ai)
--
-- Notes:
--  * IDs use IDENTITY columns; MyBatis reads the generated value back via JDBC getGeneratedKeys.
--  * Timestamps are TIMESTAMP WITH TIME ZONE so values do not depend on the JVM or DB server time zone.
--    The application always writes UTC; the DEFAULTs are only a safety net for manual inserts.
--  * COMMENT is a reserved word in Oracle, so the reviewer comment column is REVIEW_COMMENT.

CREATE TABLE ACCESS_REQUEST (
    ID              NUMBER(19)                  GENERATED BY DEFAULT AS IDENTITY,
    REQUESTER_NAME  VARCHAR2(100 CHAR)          NOT NULL,
    SYSTEM_NAME     VARCHAR2(100 CHAR)          NOT NULL,
    ACCESS_LEVEL    VARCHAR2(20 CHAR)           NOT NULL,
    REASON          VARCHAR2(1000 CHAR)         NOT NULL,
    STATUS          VARCHAR2(20 CHAR)           DEFAULT 'PENDING' NOT NULL,
    CREATED_AT      TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ACCESS_REQUEST PRIMARY KEY (ID),
    CONSTRAINT CK_ACCESS_REQUEST_STATUS CHECK (STATUS IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT CK_ACCESS_REQUEST_LEVEL  CHECK (ACCESS_LEVEL IN ('READ', 'WRITE', 'ADMIN'))
);

CREATE INDEX IX_ACCESS_REQUEST_STATUS ON ACCESS_REQUEST (STATUS);

CREATE TABLE REQUEST_HISTORY (
    ID              NUMBER(19)                  GENERATED BY DEFAULT AS IDENTITY,
    REQUEST_ID      NUMBER(19)                  NOT NULL,
    OLD_STATUS      VARCHAR2(20 CHAR),
    NEW_STATUS      VARCHAR2(20 CHAR)           NOT NULL,
    REVIEW_COMMENT  VARCHAR2(1000 CHAR),
    CHANGED_AT      TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CHANGED_BY      VARCHAR2(100 CHAR)          NOT NULL,
    CONSTRAINT PK_REQUEST_HISTORY PRIMARY KEY (ID),
    CONSTRAINT FK_REQUEST_HISTORY_REQUEST FOREIGN KEY (REQUEST_ID) REFERENCES ACCESS_REQUEST (ID),
    CONSTRAINT CK_REQUEST_HISTORY_OLD CHECK (OLD_STATUS IS NULL OR OLD_STATUS IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT CK_REQUEST_HISTORY_NEW CHECK (NEW_STATUS IN ('PENDING', 'APPROVED', 'REJECTED'))
);

-- Oracle does not index foreign key columns automatically.
CREATE INDEX IX_REQUEST_HISTORY_REQUEST ON REQUEST_HISTORY (REQUEST_ID);

CREATE TABLE NOTIFICATION_LOG (
    ID                 NUMBER(19)                  GENERATED BY DEFAULT AS IDENTITY,
    EVENT_ID           VARCHAR2(36 CHAR)           NOT NULL,
    REQUEST_ID         NUMBER(19)                  NOT NULL,
    EVENT_TYPE         VARCHAR2(50 CHAR)           NOT NULL,
    PROCESSING_STATUS  VARCHAR2(20 CHAR)           NOT NULL,
    CREATED_AT         TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    PROCESSED_AT       TIMESTAMP(6) WITH TIME ZONE,
    ERROR_MESSAGE      VARCHAR2(2000 CHAR),
    CONSTRAINT PK_NOTIFICATION_LOG PRIMARY KEY (ID),
    -- Consumer-side deduplication: the same event can only be recorded once.
    CONSTRAINT UQ_NOTIFICATION_LOG_EVENT UNIQUE (EVENT_ID),
    CONSTRAINT FK_NOTIFICATION_LOG_REQUEST FOREIGN KEY (REQUEST_ID) REFERENCES ACCESS_REQUEST (ID),
    CONSTRAINT CK_NOTIFICATION_LOG_STATUS CHECK (PROCESSING_STATUS IN ('PROCESSED', 'FAILED'))
);

CREATE INDEX IX_NOTIFICATION_LOG_REQUEST ON NOTIFICATION_LOG (REQUEST_ID);
